internal val LocalRiftSpacing = staticCompositionLocalOf { RiftSpacing() }
internal val LocalRiftSizes = staticCompositionLocalOf { RiftSizes() }
internal val LocalRiftScoreTypography = staticCompositionLocalOf { RiftScoreTypography() }

/**
 * App theme. Dark-first; [dynamicColor] uses wallpaper colors on Android 12+ when enabled.
 */
@Composable
public fun RiftTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColorScheme

        else -> LightColorScheme
    }
    CompositionLocalProvider(
        LocalRiftSpacing provides RiftSpacing(),
        LocalRiftSizes provides RiftSizes(),
        LocalRiftScoreTypography provides RiftScoreTypography(),
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = RiftMaterialTypography,
            content = content,
        )
    }
}

/** Accessors for design tokens: `RiftTheme.spacing.md`, `RiftTheme.scoreTypography.scoreLarge`, … */
public object RiftTheme {
    public val spacing: RiftSpacing
        @Composable @ReadOnlyComposable
        get() = LocalRiftSpacing.current

    public val sizes: RiftSizes
        @Composable @ReadOnlyComposable
        get() = LocalRiftSizes.current

    public val scoreTypography: RiftScoreTypography
        @Composable @ReadOnlyComposable
        get() = LocalRiftScoreTypography.current

    public val typography: Typography
        @Composable @ReadOnlyComposable
        get() = MaterialTheme.typography

    public val colorScheme: ColorScheme
        @Composable @ReadOnlyComposable
        get() = MaterialTheme.colorScheme

    public val playerColors: List<PlayerColor>
        get() = PlayerColors.all
}
